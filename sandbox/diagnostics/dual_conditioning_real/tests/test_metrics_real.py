def test_s3_L_selects_exactly_the_top_k_at_the_requested_fraction():
    rng = np.random.default_rng(0)
    target = rng.integers(1, 50, size=1000).astype(np.float64)   # dense: purity filter is a no-op
    for frac in (0.02, 0.05, 0.10):
        fg = _foreground_mask(target, frac)
        k = round(frac * 1000)
        assert fg.sum() == k                                     # realised == requested, exactly
        assert abs(fg.mean() - frac) < 1e-9
        assert set(np.flatnonzero(fg)) == set(np.argsort(target, kind="stable")[-k:])
        assert target[fg].min() >= target[~fg].max()             # genuinely the highest positions


def test_s3_L_sparse_target_does_not_degenerate_to_everything():
    """The two ways the old `target >= quantile(target, 1-frac)` selector blows up on real tracks."""
    # (a) >=98% exact zeros => quantile == 0 => `target >= 0` selects EVERY position (the 21.6%-at-100%).
    a = np.zeros(1000)
    a[:15] = np.arange(1, 16)
    assert (a >= np.quantile(a, 0.98)).mean() == 1.0                     # old: 100%
    fg = _foreground_mask(a, 0.02)
    assert fg.sum() == 15 and 0 < fg.mean() < 1.0                        # new: the 15 real peaks only
    assert set(np.flatnonzero(fg)) == set(range(15))

    # (b) heavy integer ties: counts are small integers, so the 98th percentile lands ON a tied value
    # and `>=` sweeps in the whole tie group.
    b = np.concatenate([np.zeros(600), np.ones(300), np.full(100, 9.0)])
    assert (b >= np.quantile(b, 0.98)).mean() == 0.10                    # old: 5x over-selects
    fgb = _foreground_mask(b, 0.02)
    assert fgb.sum() == 20 and fgb.mean() == 0.02                        # new: exactly 2%
    assert set(np.flatnonzero(fgb)) <= set(range(900, 1000))


def test_s3_L_degenerate_targets_are_never_empty_and_never_everything():
    for target in (np.zeros(500),                                # all-zero
                   np.concatenate([np.zeros(498), [3.0, 9.0]])): # only 2 non-zero, fewer than min_n
        fg = _foreground_mask(target, 0.02)
        assert 0 < fg.sum() < target.size
    only_two = np.concatenate([np.zeros(498), [3.0, 9.0]])
    assert set(np.flatnonzero(_foreground_mask(only_two, 0.02))) >= {498, 499}
    assert _foreground_mask(np.zeros(0), 0.02).size == 0


def test_s3_C_matches_bruteforce_and_is_deterministic():
    rng = np.random.default_rng(3)
    for _ in range(20):
        n = int(rng.integers(50, 3000))
        target = np.where(rng.random(n) < 0.6, 0.0, rng.integers(1, 200, size=n)).astype(np.float64)
        fg = _foreground_mask(target, 0.02)
        assert np.array_equal(fg, _foreground_mask(target, 0.02))          # deterministic
        # brute force: sort descending, walk down taking the k largest, then drop sub-1 counts
        k = min(n, max(5, round(0.02 * n)))
        want = np.zeros(n, bool)
        want[np.array(sorted(range(n), key=lambda i: (target[i], i))[-k:])] = True
        pos = target >= 1.0
        if int(pos.sum()) >= min(5, n):
            want &= pos
        assert np.array_equal(fg, want)
        assert fg.any() and not fg.all()
        if fg.sum():
            assert target[fg].min() >= target[~fg].max()                   # no background above signal


