class FakeS23Model(FakeM2Model):
    """Adds the two stubs the S23 sanity needs.

    `z_identity`: the decoder is BIT-EXACTLY blind to `y_meta` but its latent `z` already encodes the
    covariate. This is the case the probe exists to get right -- a probe that does not control for `z`
    reads it as "recoverable" even though the metadata pathway is dead.
    """

    def decoder(self, z, y_meta):
        if self.kind not in ("z_identity", "assay_responsive"):
            return super().decoder(z, y_meta)
        B, L, _ = z.shape
        A = y_meta.shape[2]
        if self.kind == "z_identity":
            eta = z[:, :1, 0].expand(B, L).unsqueeze(-1).expand(B, L, A) * 1.0   # from z ONLY
        else:
            aid = y_meta[:, 1, :]                                                # from y_meta ONLY
            eta = (0.7 * aid).unsqueeze(1).expand(B, L, A)
        mu = torch.pow(2.0, eta.clamp(-15, 30)).clamp_min(1e-6)
        n = torch.full_like(mu, self.n_const)
        return dict(mu=mu, n=n, p=(n / (n + mu)).clamp(1e-9, 1 - 1e-9), eta=eta, log2_mu=eta)


def _s23_units(model, n_per_assay=3, assays=(0, 1, 2, 3), B=2, L=48):
    """One unit per (assay, replicate); `z` is set to the assay id so `z_identity` can read it off."""
    units = []
    for a in assays:
        for r in range(n_per_assay):
            ym = torch.full((B, 4, 8), -1.0)
            ym[:, DEPTH_ROW, a] = 25.0
            ym[:, 1, a] = float(a)
            ym[:, READLEN_ROW, a] = 76.0
            ym[:, RUN_TYPE_ROW, a] = float(a % 2)
            z = torch.full((B, L, 2), float(a))
            imp = torch.zeros(B, L, 8, dtype=torch.bool)
            imp[:, :, a] = True
            gt = torch.zeros(B, L, 8)
            gt[:, :, a] = torch.arange(L, dtype=torch.float32).expand(B, L) + 1.0
            units.append(EvalUnit(z=z, y_meta_true=ym.clone(),
                                  den_map=torch.zeros(B, L, 8, dtype=torch.bool),
                                  y_data=torch.zeros(B, L, 8), imp_map=imp, y_data_imp=gt,
                                  y_meta_imp=ym.clone(), y_avail=torch.zeros(B, 8),
                                  biosample=f"T_b{a}", imp_biosample=f"V_b{a}_{r}"))
    return units


