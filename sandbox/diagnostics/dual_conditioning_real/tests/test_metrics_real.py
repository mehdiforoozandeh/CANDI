def test_s1_L_ablation_is_not_fooled_by_a_presence_detector():
    """LOAD-BEARING sentinel control (the h47 V2 anchor protocol fails this one).

    A decoder that reacts only to the MISSING sentinel -- "is this slot present?" -- and is bit-exactly
    blind to assay IDENTITY must read ZERO on an assay-identity probe. A whole-row `assay_id`
    permutation does not: it slides the sentinel across slots and reports a large response.
    """
    m = FakeM2Model("assay_presence_only", rt_gain=3.0)
    units = [_m2_unit(m, a=0, seed=0), _m2_unit(m, a=1, seed=1)]

    honest = _metadata_ablation(m, units, 1, fg_frac=0.5, seed=0)      # row 1 = assay_id, real -> real
    assert honest["n_targets"] == 2
    assert honest["max_abs_d_eta"] == 0.0 and honest["mean_d_crps"] == 0.0
    assert not honest["uses_covariate"]                                # correct verdict: identity-blind

    # the contaminated protocol: permute the WHOLE assay_id row, measure max|d eta| over every slot.
    u = units[0]
    ym = u.y_meta_true.clone()
    ym[:, 1, :] = torch.roll(u.y_meta_true[:, 1, :], shifts=1, dims=1)
    fooled = (m.decoder(u.z, ym)["eta"] - m.decoder(u.z, u.y_meta_true)["eta"]).abs().max().item()
    assert fooled > 1.0                                                # ...reads "steering" on a blind model


