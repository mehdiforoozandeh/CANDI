# ---------------------------------------------------------------------------
# S1 (h48) — TOTAL told-depth slope + cross-target metadata ablation
#
# `eta_slope` scores the offset-FREE residual, so it measures WHERE the depth response is implemented,
# not WHETHER the model responds (audit S1). The primary instrument is the TOTAL slope
# d<log2_mu>/d(told depth), which must read 1.0 for a correct exposure model however it is built.
# ---------------------------------------------------------------------------

def _bruteforce_total_slope(model, u, a, fg_frac):
    """Independent recomputation of the total told-depth slope: hand-built mask + gather, and a
    least-squares fit via `np.linalg.lstsq` (the instrument uses `np.polyfit`)."""
    m = u.imp_map[:, :, a]
    tgt = u.y_data_imp[:, :, a][m].double().cpu().numpy()
    fg = tgt >= np.quantile(tgt, 1.0 - fg_frac)
    if fg.sum() < 5:
        fg = np.ones_like(fg, bool)
    base_d = u.y_meta_imp[:, DEPTH_ROW, a]
    xs, ys = [], []
    for k in (1, 2, 4, 8):
        dvec = base_d - float(np.log2(k))
        ym = u.y_meta_true.clone()
        ym[:, DEPTH_ROW, a] = dvec
        lm = model.decoder(u.z, ym)["log2_mu"][:, :, a][m].double().cpu().numpy()
        xs.append(float(dvec.float().mean()))
        ys.append(float(lm[fg].mean()))
    design = np.vstack([np.array(xs), np.ones(len(xs))]).T
    return float(np.linalg.lstsq(design, np.array(ys), rcond=None)[0][0])


