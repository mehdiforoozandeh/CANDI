def _nb_sample(mu, n, size, seed):
    p = n / (n + mu)
    return nbinom.rvs(n, p, size=size, random_state=np.random.default_rng(seed)).astype(np.float64)


def test_s5_L_oracle_recovers_an_injected_scale():
    """mu = truth * 2^c0 => c* must recover -c0 and the residual must fall to the shape floor."""
    n_true, mu_true = 4.0, 12.0
    y = _nb_sample(mu_true, n_true, 20000, 0)
    n = np.full_like(y, n_true)
    for c0 in (-2.0, -0.75, 0.0, 1.5):
        mu = np.full_like(y, mu_true * 2.0 ** c0)
        r = _oracle_scale(mu, n, y, seed=0)
        assert abs(r["c_star"] + c0) < 0.06                          # recovers -c0
        crps = float(np.mean(nb_crps(n, np.clip(n / (n + mu), 1e-9, 1 - 1e-9), y)))
        floor = float(np.mean(nb_crps(n, np.clip(n / (n + mu_true), 1e-9, 1 - 1e-9), y)))
        assert r["crps_oracle_scaled"] == pytest.approx(floor, rel=0.02)   # drops TO the shape floor
        assert crps - r["crps_oracle_scaled"] >= -1e-9                     # scale_error is non-negative
        if abs(c0) > 0.5:
            assert crps > r["crps_oracle_scaled"] * 1.05             # a real scale error is exposed


def test_s5_L_correct_scale_wrong_shape_leaves_the_error_in_capability():
    """Right level, wrong per-position shape => c* ~ 0 and the error stays in the capability term."""
    n_true = 4.0
    lam = np.repeat([2.0, 40.0], 10000)                              # two-level truth
    y = np.array([_nb_sample(m, n_true, 1, s)[0] for s, m in enumerate(lam)])
    mu = np.full_like(y, float(lam.mean()))                          # correct MEAN, no shape at all
    n = np.full_like(y, n_true)
    r = _oracle_scale(mu, n, y, seed=0)
    crps = float(np.mean(nb_crps(n, np.clip(n / (n + mu), 1e-9, 1 - 1e-9), y)))
    assert abs(r["c_star"]) < 0.75                                   # little scale left to fix
    assert (crps - r["crps_oracle_scaled"]) < 0.25 * r["crps_oracle_scaled"]   # error is capability


def test_s5_C_marginal_matches_a_bruteforce_grid_and_is_never_a_point_mass():
    rng = np.random.default_rng(0)
    for zero_frac in (0.4, 0.7, 0.95):                                # 4/8 real assays have median 0
        y = np.where(rng.random(8000) < zero_frac, 0.0,
                     _nb_sample(20.0, 3.0, 8000, 1) + 1.0)
        m = _marginal_nb(y)
        if zero_frac >= 0.7:
            assert m["marg_mu_legacy_median"] < 1e-3                 # legacy: a point mass at 0...
            assert m["marg_crps_legacy_median"] == pytest.approx(float(y.mean()), rel=0.02)  # ...= mean(y)
        assert m["marg_mu"] > 0.0                                    # honest: never a point mass
        assert m["marg_crps"] <= m["marg_crps_legacy_median"] + 1e-9  # ...and never worse
        # brute force over an independent, finer grid evaluated on the raw samples (no histogram)
        best = min(
            (float(np.mean(nb_crps(np.full_like(y, nn), np.clip(nn / (nn + mm), 1e-9, 1 - 1e-9), y))),
             mm, nn)
            for mm in np.geomspace(max(y.mean(), 1e-3) / 6, max(y.mean(), 1e-3) * 6, 25)
            for nn in np.geomspace(0.05, 50.0, 15))
        assert m["marg_crps"] <= best[0] * 1.02


def test_s5_C_decomposition_is_additive_and_ordered():
    y = _nb_sample(10.0, 3.0, 5000, 2)
    n = np.full_like(y, 3.0)
    mu = np.full_like(y, 40.0)                                       # 4x too high
    r = _oracle_scale(mu, n, y, seed=0)
    crps = float(np.mean(nb_crps(n, np.clip(n / (n + mu), 1e-9, 1 - 1e-9), y)))
    scale_error = crps - r["crps_oracle_scaled"]
    assert r["crps_oracle_scaled"] + scale_error == pytest.approx(crps, abs=1e-12)   # additive
    assert scale_error > 0                                           # a 4x level error is fixable...
    assert r["crps_oracle_scaled_and_n"] <= r["crps_oracle_scaled"] + 1e-9   # ...n-oracle only helps
    assert _oracle_scale(mu, n, y, seed=0)["c_star"] == r["c_star"]  # deterministic


