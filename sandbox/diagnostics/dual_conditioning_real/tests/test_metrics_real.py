class FakeEncoder:
    """encode() -> a latent with a KNOWN invariance property; decoder unused for M3."""

    STRIDE = 32

    def __init__(self, kind, seed=0):
        self.kind = kind
        # projection of DNA sampled across the whole window (region-specific, DSF-invariant)
        n_pos = (19200 + self.STRIDE - 1) // self.STRIDE
        self.P = np.random.default_rng(seed).normal(size=(n_pos * 4, 8)).astype(np.float32)

    def eval(self):
        return self

    def _region_sig(self, x_dna, B):
        flat = x_dna[:, ::self.STRIDE, :].reshape(B, -1).float().cpu().numpy()
        return flat @ self.P                                 # [B, 8]

    def encode(self, x_data, x_dna, x_meta):
        B = x_data.shape[0]
        if self.kind == "invariant":                         # region sig from DNA only (DSF-invariant)
            z = torch.tensor(self._region_sig(x_dna, B), dtype=torch.float32) + 1.0   # bias -> nonzero norm
        elif self.kind == "non_invariant":                   # rotates with input depth (DSF-varying)
            d = x_meta[:, DEPTH_ROW, :].clamp_min(0).float().mean(dim=1)
            rot = torch.stack([torch.cos(3.0 * d), torch.sin(3.0 * d)], dim=1)         # [B, 2]
            z = rot + 0.01 * torch.tensor(self._region_sig(x_dna, B)[:, :2], dtype=torch.float32)
        elif self.kind == "collapsed":                       # constant latent
            z = torch.ones(B, 4)
        else:
            raise ValueError(self.kind)
        return z.unsqueeze(1)                                 # [B, 1, d]


