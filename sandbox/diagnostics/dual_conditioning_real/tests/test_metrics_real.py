class FakeM2Model:
    """decoder(z, y_meta) -> {mu,n,p,eta,log2_mu} following a chosen law; encode() -> dummy z."""

    def __init__(self, kind, center=25.0, n_const=5.0, slope=1.0, rt_gain=3.0, const_log2mu=3.0,
                 clamp_lo=-float("inf"), clamp_hi=float("inf")):
        self.kind, self.center, self.n_const = kind, center, n_const
        self.slope, self.rt_gain, self.const_log2mu = slope, rt_gain, const_log2mu
        self.clamp_lo, self.clamp_hi = clamp_lo, clamp_hi        # mirrors the real decoder's log2_mu clamp

    def encode(self, x_data, x_dna, x_meta):
        B, L, _ = x_data.shape
        return torch.zeros(B, L, 2)

    def decoder(self, z, y_meta):
        B, L, _ = z.shape
        A = y_meta.shape[2]
        depth = y_meta[:, DEPTH_ROW, :]
        rt = y_meta[:, RUN_TYPE_ROW, :]
        if self.kind == "offset_only":                       # mu=2^(d-center), eta=0 (pure arithmetic)
            log2mu = depth - self.center
            eta = torch.zeros_like(depth)
        elif self.kind == "eta_depth":                       # eta tracks depth (learned), offset off
            eta = self.slope * (depth - self.center)
            log2mu = eta
        elif self.kind == "offset_plus_eta":                 # HYBRID: offset AND a learned eta response
            eta = self.slope * (depth - self.center)
            log2mu = (depth - self.center) + eta             # total slope = 1 + slope
        elif self.kind == "depth_ignore":                    # constant, depth ignored
            eta = torch.full_like(depth, self.const_log2mu)
            log2mu = eta
        elif self.kind == "rt_responsive":                   # mu depends on run_type
            gain = torch.where(rt == 1.0, torch.full_like(rt, self.rt_gain), torch.ones_like(rt))
            log2mu = (depth - self.center) + torch.log2(gain)
            eta = torch.zeros_like(depth)
        elif self.kind == "rt_ignore":                       # run_type ignored
            log2mu = depth - self.center
            eta = torch.zeros_like(depth)
        elif self.kind == "assay_presence_only":
            # Responds ONLY to "is this slot present?" (assay_id == MISSING sentinel), and is bit-exactly
            # blind to WHICH assay it is. A whole-row assay_id permutation moves the sentinel across
            # slots and reads this as large "assay steering"; the honest probe must read zero.
            aid = y_meta[:, 1, :]
            eta = torch.where(aid < 0, torch.full_like(aid, self.rt_gain), torch.zeros_like(aid))
            log2mu = (depth - self.center) + eta
        else:
            raise ValueError(self.kind)
        log2mu = log2mu.clamp(self.clamp_lo, self.clamp_hi)
        mu = torch.pow(2.0, log2mu).clamp_min(1e-6)
        n = torch.full_like(mu, self.n_const)
        p = (n / (n + mu)).clamp(1e-9, 1.0 - 1e-9)
        exp = lambda t: t.unsqueeze(1).expand(B, L, A)
        return dict(mu=exp(mu), n=exp(n), p=exp(p), eta=exp(eta), log2_mu=exp(log2mu))


def _m2_unit(model, *, true_depth=25.0, true_rt=1.0, a=0, B=4, L=64, seed=0) -> EvalUnit:
    """Synthetic held-out-target unit whose GT is generated by `model` at the TRUE prompt."""
    ym = torch.full((B, 4, 8), -1.0)
    ym[:, DEPTH_ROW, a] = true_depth
    ym[:, 1, a] = float(a)
    ym[:, READLEN_ROW, a] = 76.0
    ym[:, RUN_TYPE_ROW, a] = true_rt
    out = model.decoder(torch.zeros(B, L, 2), ym)
    mu = out["mu"][:, :, a].numpy()
    n = out["n"][:, :, a].numpy()
    p = np.clip(n / (n + mu), 1e-9, 1.0 - 1e-9)
    gt = nbinom.rvs(n, p, random_state=np.random.default_rng(seed)).astype(np.float64)
    y_data_imp = torch.full((B, L, 8), -1.0)
    y_data_imp[:, :, a] = torch.tensor(gt, dtype=torch.float32)
    imp_map = torch.zeros(B, L, 8, dtype=torch.bool)
    imp_map[:, :, a] = True
    return EvalUnit(z=torch.zeros(B, L, 2), y_meta_true=ym.clone(),
                    den_map=torch.zeros(B, L, 8, dtype=torch.bool), y_data=torch.zeros(B, L, 8),
                    imp_map=imp_map, y_data_imp=y_data_imp, y_meta_imp=ym.clone(),
                    y_avail=torch.zeros(B, 8), biosample="T_x", imp_biosample="B_x")


